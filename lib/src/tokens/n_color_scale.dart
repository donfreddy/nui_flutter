import 'dart:math' as math;
import 'package:flutter/material.dart';

/// A full 11-step color scale (50 → 950) generated from a single seed color.
///
/// Each step is accessible both by index (`scale[0]` = shade 50) and by named
/// getter (`scale.s50`, `scale.s500`, etc.).
///
/// ## Usage
///
/// ```dart
/// // Generate an entire scale from one brand color:
/// final violet = NColorScale.fromSeed(Color(0xFF7C3AED));
///
/// // Access individual shades:
/// violet.s500   // the seed shade
/// violet.s100   // a very light tint
/// violet.s900   // a very dark shade
///
/// // Override specific shades after generation:
/// final custom = NColorScale.fromSeed(
///   Color(0xFF7C3AED),
///   overrides: {200: Color(0xFFEDE9FE)},
/// );
/// ```
///
/// ## How generation works
///
/// The seed becomes shade `500`. Lighter shades (50–400) are generated by
/// mixing the seed with white (increasing proportions). Darker shades (600–950)
/// are generated by mixing with black. The approach mirrors Tailwind's color
/// generation heuristics and matches the Nuxt UI CSS variable system.
@immutable
class NColorScale {
  /// Creates a scale from an explicit list of 11 shades.
  ///
  /// [shades] must contain exactly 11 colors in ascending order:
  /// [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950].
  const NColorScale(this.shades)
      : assert(shades.length == 11, 'NColorScale requires exactly 11 shades');

  /// The 11 resolved colors indexed as: 0→50, 1→100, …, 10→950.
  final List<Color> shades;

  // ---------------------------------------------------------------------------
  // fromSeed factory
  // ---------------------------------------------------------------------------

  /// Generates a full 11-step scale from a single [seed] color.
  ///
  /// The [seed] is placed at shade 500 (index 5). Lighter shades are generated
  /// by mixing toward white; darker shades toward black.
  ///
  /// Optional [overrides] let you replace individual steps after generation
  /// using the shade number as key (e.g. `{200: Color(0xFFEDE9FE)}`).
  factory NColorScale.fromSeed(
    Color seed, {
    Map<int, Color>? overrides,
  }) {
    // Ratios at which we mix white (0.0) → seed (1.0) for lighter shades
    // and seed (1.0) → black (0.0) for darker shades.
    // These are tuned to approximate Tailwind's perceived-lightness ramps.
    const lighterMix = [
      0.06, // 50   (very light tint)
      0.13, // 100
      0.28, // 200
      0.44, // 300
      0.72, // 400
    ];
    const darkerMix = [
      0.72, // 600 (slightly darker than seed)
      0.56, // 700
      0.40, // 800
      0.22, // 900
      0.10, // 950 (very dark shade)
    ];

    const white = Color(0xFFFFFFFF);
    const black = Color(0xFF000000);

    final generated = <Color>[
      for (final t in lighterMix) _mixOklab(white, seed, t),
      seed, // shade 500
      for (final t in darkerMix) _mixOklab(seed, black, 1 - t),
    ];

    // Apply overrides
    if (overrides != null) {
      const shadeKeys = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
      for (final entry in overrides.entries) {
        final idx = shadeKeys.indexOf(entry.key);
        if (idx >= 0) generated[idx] = entry.value;
      }
    }

    return NColorScale(List.unmodifiable(generated));
  }

  // ---------------------------------------------------------------------------
  // Named shade accessors
  // ---------------------------------------------------------------------------

  /// Shade 50: lightest tint.
  Color get s50 => shades[0];

  /// Shade 100.
  Color get s100 => shades[1];

  /// Shade 200.
  Color get s200 => shades[2];

  /// Shade 300.
  Color get s300 => shades[3];

  /// Shade 400.
  Color get s400 => shades[4];

  /// Shade 500: the seed / mid shade.
  Color get s500 => shades[5];

  /// Shade 600.
  Color get s600 => shades[6];

  /// Shade 700.
  Color get s700 => shades[7];

  /// Shade 800.
  Color get s800 => shades[8];

  /// Shade 900.
  Color get s900 => shades[9];

  /// Shade 950: darkest.
  Color get s950 => shades[10];

  // ---------------------------------------------------------------------------
  // Shade by step name
  // ---------------------------------------------------------------------------

  /// Returns the color for a given [step] key (50, 100, … 950).
  ///
  /// Throws [ArgumentError] for unknown steps.
  Color shade(int step) {
    const map = {
      50: 0,
      100: 1,
      200: 2,
      300: 3,
      400: 4,
      500: 5,
      600: 6,
      700: 7,
      800: 8,
      900: 9,
      950: 10,
    };
    final idx = map[step];
    if (idx == null) throw ArgumentError('Unknown shade step: $step');
    return shades[idx];
  }

  // ---------------------------------------------------------------------------
  // Lerp
  // ---------------------------------------------------------------------------

  /// Linearly interpolates between two scales.
  static NColorScale lerp(NColorScale a, NColorScale b, double t) {
    return NColorScale(
      List.generate(11, (i) => Color.lerp(a.shades[i], b.shades[i], t)!),
    );
  }

  // ---------------------------------------------------------------------------
  // Light-mode semantic token helpers
  // ---------------------------------------------------------------------------

  /// Returns the recommended solid (main) color for light mode: shade 500.
  Color get solidLight => s500;

  /// Returns the recommended solid (main) color for dark mode: shade 400.
  Color get solidDark => s400;

  /// Returns a soft background tint for light mode: shade 50.
  Color get softBgLight => s50;

  /// Returns a soft background tint for dark mode: shade 950 (with opacity).
  Color get softBgDark => s950.withValues(alpha: 0.3);

  /// Returns the tinted border for light mode: shade 200.
  Color get borderLight => s200;

  /// Returns the tinted border for dark mode: shade 800.
  Color get borderDark => s800;

  /// Returns the tinted text for light mode: shade 700.
  Color get textLight => s700;

  /// Returns the tinted text for dark mode: shade 300.
  Color get textDark => s300;

  // ---------------------------------------------------------------------------
  // Well-known built-in palettes
  // ---------------------------------------------------------------------------

  /// Nuxt UI signature green (#00DC82 → 500).
  static final NColorScale green =
      NColorScale.fromSeed(const Color(0xFF00DC82)); 
      
  /// Emerald for success states.
  static final NColorScale emerald =
      NColorScale.fromSeed(const Color(0xFF10B981));

  /// Neutral blue for secondary actions.
  static final NColorScale blue = NColorScale.fromSeed(const Color(0xFF3B82F6));

  /// Sky blue for info states.
  static final NColorScale sky = NColorScale.fromSeed(const Color(0xFF0EA5E9));

  /// A predefined amber scale.
  static final amber = NColorScale.fromSeed(const Color(0xFFF59E0B));

  /// A predefined cool gray (slate) scale.
  static final slate = NColorScale.fromSeed(const Color(0xFF64748B));

  /// A predefined neutral-cool gray (zinc) scale.
  static final zinc = NColorScale.fromSeed(const Color(0xFF71717A));

  /// A predefined true gray (neutral) scale.
  static final neutral = NColorScale.fromSeed(const Color(0xFF737373));

  /// A predefined warm gray (stone) scale.
  static final stone = NColorScale.fromSeed(const Color(0xFF78716C));

  /// Red for errors.
  static final NColorScale red = NColorScale.fromSeed(const Color(0xFFEF4444));

  /// Orange: default nui_flutter primary brand.
  static final NColorScale orange =
      NColorScale.fromSeed(const Color(0xFFF97316));

  /// Violet / purple.
  static final NColorScale violet =
      NColorScale.fromSeed(const Color(0xFFA855F7));

  // ---------------------------------------------------------------------------
  // Equality / hashCode
  // ---------------------------------------------------------------------------

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is NColorScale &&
          const ListEquality<Color>().equals(shades, other.shades);

  @override
  int get hashCode => Object.hashAll(shades);

  @override
  String toString() => 'NColorScale(seed≈${s500.toARGB32().toRadixString(16)})';
}

// ---------------------------------------------------------------------------
// Oklab interpolation for perceptually uniform colour ramps
// (Björn Ottosson's Oklab – https://bottosson.github.io/posts/oklab/)
// ---------------------------------------------------------------------------

/// Linearises a single sRGB channel [c] in [0..1].
double _srgbToLinear(double c) =>
    c <= 0.04045 ? c / 12.92 : math.pow((c + 0.055) / 1.055, 2.4).toDouble();

/// Converts a linear channel back to sRGB.
double _linearToSrgb(double c) =>
    c <= 0.0031308 ? 12.92 * c : 1.055 * math.pow(c, 1.0 / 2.4) - 0.055;

/// Converts a Flutter [Color] (assumed sRGB) into Oklab components.
(List<double> lms, double L, double a, double b) _toOklab(Color color) {
  final r = _srgbToLinear(color.r);
  final g = _srgbToLinear(color.g);
  final bl = _srgbToLinear(color.b);

  // Linear sRGB → LMS (Oklab matrix)
  final l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * bl;
  final m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * bl;
  final s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * bl;

  final lC = math.pow(l, 1.0 / 3.0);
  final mC = math.pow(m, 1.0 / 3.0);
  final sC = math.pow(s, 1.0 / 3.0);

  return (
    [l, m, s],
    0.2104542553 * lC + 0.7936177850 * mC - 0.0040720468 * sC,
    1.9779984951 * lC - 2.4285922050 * mC + 0.4505937099 * sC,
    0.0259040371 * lC + 0.7827717662 * mC - 0.8086757660 * sC,
  );
}

/// Converts Oklab components back to a Flutter [Color].
Color _fromOklab(double L, double a, double b, double alpha) {
  // Oklab → LMS'
  final lP = L + 0.3963377774 * a + 0.2158037573 * b;
  final mP = L - 0.1055613458 * a - 0.0638541728 * b;
  final sP = L - 0.0894841775 * a - 1.2914855480 * b;

  // LMS' → LMS (cube)
  final l = lP * lP * lP;
  final m = mP * mP * mP;
  final s = sP * sP * sP;

  // LMS → Linear sRGB
  final r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s;
  final g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s;
  final bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s;

  return Color.from(
    alpha: alpha,
    red: _linearToSrgb(r),
    green: _linearToSrgb(g),
    blue: _linearToSrgb(bl),
  );
}

/// Linearly interpolates between two [Color]s in Oklab space.
Color _mixOklab(Color a, Color b, double t) {
  final (_, la, aa, ba) = _toOklab(a);
  final (_, lb, ab, bb) = _toOklab(b);
  final alpha = a.a + (b.a - a.a) * t;
  return _fromOklab(
    la + (lb - la) * t,
    aa + (ab - aa) * t,
    ba + (bb - ba) * t,
    alpha,
  );
}

/// Minimal list-equality helper (avoids adding `collection` dep).
class ListEquality<E> {
  const ListEquality();
  bool equals(List<E> a, List<E> b) {
    if (identical(a, b)) return true;
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }
}
